"""S-005: generate the umbrella capability catalog from the verified index.

The catalog (taffee-core/catalog/capabilities.yaml) is a view of the index, never a source. This module
reads only the index, through the S-002 loader, so a bad index writes nothing.
"""

import argparse
import os
import re
import sys
from pathlib import Path

import yaml

from .registry import RegistryError, load_index

REPO = "taffee-capabilities"
COMMIT = re.compile(r"^[0-9a-f]{40}$")
HEADER = """\
# Capability catalog for the capabilities pillar. Lists what is reusable and the label each entry has earned.
# GENERATED by taffee-capabilities (python -m capability.catalog_export) from its verified index. Do not edit by hand.
# Source of truth for each entry is the manifest in the taffee-capabilities repository (catalog/<kind>/<name>/manifest.yaml).
# Labels are computed from evidence under the policy_version below, and are never written in a manifest.
# index_version is the taffee-capabilities commit the index was built from, supplied by the caller (null when none was given).
"""


class CatalogError(Exception):
    """The catalog could not be generated. Nothing was written."""


def _version_key(version: str) -> tuple[int, int, int]:
    major, minor, patch = (int(part) for part in version.split("."))
    return major, minor, patch


def _source(entry: dict) -> str | None:
    if entry["kind"] == "tool":
        return f"{REPO}/library/{entry['name']}" if entry.get("implementations") else None
    source = entry["source"]
    if source["type"] == "external":
        return f"{source['repository']}@{source['commit']}:{source['path']}"
    return f"{REPO}/{source['location']}"


def _evidence(entry: dict) -> str | None:
    if entry["kind"] != "tool":
        return None
    if entry["label"] == "Tested":
        return f"{REPO}/evidence/tools/{entry['name']}/{entry['version']}/"
    if entry["label"] == "Validated":
        return f"{REPO}/library/{entry['name']}/conformance.json"
    return None


def catalog_entry(entry: dict) -> dict:
    """One catalog entry from one index entry. Pure: it opens nothing."""
    return {
        "name": entry["name"],
        "kind": entry["kind"],
        "version": entry["version"],
        "digest": entry["identity"] if entry["kind"] == "tool" else entry["manifest_digest"],
        "label": entry["label"],
        "owner": entry["manifest"]["owner"],
        "summary": entry["manifest"]["summary"],
        "source": _source(entry),
        "evidence": _evidence(entry),
    }


def build_catalog(root, commit: str | None = None) -> dict:
    """The catalog as data. Raises CatalogError for a bad index or a malformed commit."""
    if commit is not None and not COMMIT.match(commit):
        raise CatalogError("commit must be 40 lowercase hex characters")
    try:
        index = load_index(Path(root))
    except RegistryError as exc:
        raise CatalogError(str(exc)) from exc
    entries = sorted(index["entries"], key=lambda e: (e["kind"], e["name"], _version_key(e["version"])))
    return {
        "version": 1,
        "pillar": "capabilities",
        "repo": REPO,
        "policy_version": index["policy_version"],
        "inputs_digest": index["inputs_digest"],
        "index_digest": index["index_digest"],
        "index_version": commit,
        "entries": [catalog_entry(entry) for entry in entries],
    }


def render(catalog: dict) -> bytes:
    """Deterministic text: the header, then the YAML body."""
    body = yaml.safe_dump(catalog, sort_keys=False, default_flow_style=False, allow_unicode=True, width=10_000)
    return (HEADER + body).encode("utf-8")


def write_catalog(root, out, commit: str | None = None) -> Path:
    """Generate and write the catalog atomically. On error the existing file is untouched."""
    data = render(build_catalog(root, commit))
    out = Path(out)
    temp = out.with_name(out.name + ".tmp")
    try:
        temp.write_bytes(data)
        os.replace(temp, out)
    finally:
        if temp.exists():
            temp.unlink()
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="capability-catalog")
    parser.add_argument("--root", default=".", help="the taffee-capabilities root, holding index/index.json")
    parser.add_argument("--out", required=True, help="where to write the catalog, for example taffee-core/catalog/capabilities.yaml")
    parser.add_argument("--commit", help="the 40-hex commit the index was built from (omit when unknown)")
    args = parser.parse_args(argv)
    if args.commit is not None and not COMMIT.match(args.commit):
        parser.error("--commit must be 40 lowercase hex characters")
    try:
        path = write_catalog(args.root, args.out, args.commit)
    except (CatalogError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
